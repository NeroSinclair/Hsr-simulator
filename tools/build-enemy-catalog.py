"""Build an offline enemy index from cached public game-data snapshots.

Inputs downloaded separately into .preview-equipment (not shipped):
FortOfFans/HSRMaps/master/en/monster.json and gacha.gg's enemy index HTML.
Only factual identity, classification and numeric combat fields are retained.
No descriptions, skill text or third-party guide prose is redistributed.
"""
import collections
import html
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / '.preview-equipment'
raw = json.loads((CACHE / 'all-monsters.json').read_text(encoding='utf-8-sig'))
page = (CACHE / 'enemy-index.html').read_text(encoding='utf-8')
public = {}
normalize = lambda name: re.sub(r'[^a-z0-9]', '', html.unescape(name).lower())
for button in re.findall(r'<button\b[^>]*>(.*?)</button>', page, re.S):
    icon = re.search(r'mostericon-monster_(\d+)', button)
    name = re.search(r'<span class="text-lg leading-snug[^>]*>(.*?)</span>', button, re.S)
    category = re.search(r'<span class="block truncate text-base text-muted">(.*?)</span>', button, re.S)
    if icon and name:
        name = html.unescape(re.sub('<[^>]+>', '', name[1]))
        public[normalize(name)] = {'name': name, 'icon': icon[1], 'faction': html.unescape(category[1]) if category else 'Other'}

groups = collections.defaultdict(list)
for key, monster in raw.items():
    if monster.get('name') and monster.get('stats'):
        groups[monster['name']].append(monster)
rows = []
for name, variants in sorted(groups.items()):
    variants.sort(key=lambda m: (len(str(m['id'])), str(m['id'])))
    base = variants[0]
    indexed = public.get(normalize(name), {})
    rank = base['rank']
    kind = 'boss' if rank in ['LittleBoss', 'BigBoss'] else 'elite' if rank == 'Elite' else 'normal'
    if indexed.get('faction') == 'Other' and kind == 'normal':
        kind = 'special'
    rows.append({
        'name': name, 'id': str(base['id']), 'icon': indexed.get('icon', re.sub(r'\D', '', base['shortIcon'])) or 'unknown',
        'faction': indexed.get('faction', 'Lainnya'), 'kind': kind,
        'variants': [{
            'id': str(m['id']), 'weak': ['Lightning' if w == 'Thunder' else w for w in m.get('weakness', [])],
            'hp': m['stats']['baseHealth'], 'spd': m['stats']['speed'],
            'tough': m['stats']['baseStance'] / 3, 'rank': m['rank']
        } for m in variants]
    })

# Preserve index-only identities too; no weaknesses or stats are invented.
known_names = {normalize(m['name']) for m in rows}
for key, indexed in public.items():
    if key not in known_names:
        rows.append({'name': indexed['name'], 'id': 'index-' + indexed['icon'],
                     'icon': indexed['icon'], 'faction': indexed['faction'],
                     'kind': 'special', 'variants': []})
rows.sort(key=lambda m: m['name'].lower())
assert len(rows) >= 479, 'Incomplete snapshot'
assert len({m['name'] for m in rows}) == len(rows)
assert all(m['icon'].isdigit() or m['icon'] == 'unknown' for m in rows)
output = "'use strict';\n// Game-data snapshot imported 2026-11-08. Generated by tools/build-enemy-catalog.py.\n"
output += 'const freeEnemyCatalog=' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n'
output += 'const freeEnemySources=' + json.dumps([
    ['HSRMaps · data monster', 'https://github.com/FortOfFans/HSRMaps/blob/master/en/monster.json'],
    ['Gacha.gg · indeks gambar & faksi', 'https://www.gacha.gg/honkai-star-rail/enemies'],
    ['HoYoWiki · daftar musuh', 'https://wiki.hoyolab.com/pc/hsr/aggregate/enemy?lang=en-us']
], ensure_ascii=False) + ';\n'
(ROOT / 'free-enemies-data.js').write_text(output, encoding='utf-8')
print(f'Generated {len(rows)} enemies, {sum(len(m["variants"]) for m in rows)} variants; {len(public)} public index entries.')
